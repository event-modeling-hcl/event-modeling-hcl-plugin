#!/bin/sh
# build-contract.sh publishes installable method, permission, and HCL references
# for the event-modeling-skills plugin (DP0).
#
# Usage: scripts/build-contract.sh [--check]
#
# Each method skill lists its sections in its front matter, for example:
#   metadata:
#     contract: "K0 K1 K8 K9 H0 H2 H10"
# K sections come from contract/method.md, H sections from
# contract/hcl-binding.md. Every method skill receives K13 permissions.
# The language skill receives the same policy and the complete HCL binding.
#
# With --check, the script changes nothing. It exits 1 when a copy differs
# from what the sources give, or when a skill names an unknown section.
#
# Exit status: 0 done or equal, 1 failure or difference, 2 usage error.
set -eu

check=0
case ${1:-} in
--check) check=1 ;;
'') ;;
*)
	echo "usage: scripts/build-contract.sh [--check]" >&2
	exit 2
	;;
esac

root=$(cd "$(dirname "$0")/.." && pwd)
method=$root/contract/method.md
binding=$root/contract/hcl-binding.md
skills=$root/plugins/emhcl-skills/skills

# section FILE ID prints the section "## ID ..." of FILE up to the next "## ".
section() {
	awk -v id="$2" '
		/^## / { on = ($2 == id) }
		on { print }
	' "$1"
}

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT INT TERM
failures=0
count=0
for skill_md in "$skills"/eventmodeling-*/SKILL.md; do
	dir=$(dirname "$skill_md")
	name=$(basename "$dir")
	ids=$(sed -n '2,/^---$/s/^[[:space:]]*contract:[[:space:]]*"\{0,1\}\([^"]*\)"\{0,1\}[[:space:]]*$/\1/p' "$skill_md")
	if [ -z "$ids" ]; then
		echo "build-contract: $name has no metadata.contract" >&2
		failures=$((failures + 1))
		continue
	fi
	case " $ids " in
	*" K13 "*) ;;
	*) ids="$ids K13" ;;
	esac
	{
		echo "# Contract sections of $name"
		echo
		echo "Generated by scripts/build-contract.sh from contract/method.md and"
		echo "contract/hcl-binding.md. Do not edit this file. Follow each section below."
		echo "Sections K0 to K13 hold the method. Sections H0 to H11 apply only to an"
		echo "\`.em.hcl\` model."
	} >"$tmp"
	for id in $ids; do
		case $id in
		K*) src=$method ;;
		H*) src=$binding ;;
		*)
			echo "build-contract: $name names the unknown section $id" >&2
			failures=$((failures + 1))
			continue
			;;
		esac
		text=$(section "$src" "$id")
		if [ -z "$text" ]; then
			echo "build-contract: $name names the missing section $id" >&2
			failures=$((failures + 1))
			continue
		fi
		printf '\n%s\n' "$text" >>"$tmp"
	done
	out=$dir/references/contract.md
	if [ $check -eq 1 ]; then
		if ! cmp -s "$tmp" "$out"; then
			echo "build-contract: $name/references/contract.md differs from contract/" >&2
			failures=$((failures + 1))
		fi
	else
		mkdir -p "$dir/references"
		cp "$tmp" "$out"
	fi
	count=$((count + 1))
done

# Publish the shared authorities inside the installed language skill.
publish() {
	out=$1
	if [ "$check" -eq 1 ]; then
		if ! cmp -s "$tmp" "$out"; then
			echo "build-contract: $out differs from contract/" >&2
			failures=$((failures + 1))
		fi
	else
		mkdir -p "$(dirname "$out")"
		cp "$tmp" "$out"
	fi
}

{
	echo "# Shared edit policy"
	echo
	echo "Generated by scripts/build-contract.sh from contract/method.md."
	echo "Do not edit this file. Follow K13 before changing an existing model."
	echo
	section "$method" K13
} >"$tmp"
if ! section "$method" K13 | grep -q '^## K13 '; then
	echo "build-contract: missing K13 edit permissions" >&2
	failures=$((failures + 1))
else
	publish "$skills/event-modeling-hcl/references/edit-policy.md"
fi
{
	echo "<!-- Generated by scripts/build-contract.sh from contract/hcl-binding.md. Do not edit. -->"
	echo
	cat "$binding"
} >"$tmp"
publish "$skills/event-modeling-hcl/references/hcl-binding.md"

[ $count -gt 0 ] || {
	echo "build-contract: no method skill in $skills" >&2
	exit 1
}
[ $failures -eq 0 ] || exit 1
if [ $check -eq 1 ]; then
	echo "build-contract: $count contract copies are current"
else
	echo "build-contract: wrote $count contract copies"
fi
